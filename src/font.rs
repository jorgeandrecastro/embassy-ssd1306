/// Convertit un caractère ASCII en index de glyphe.
///
/// Les minuscules utilisent les glyphes des majuscules.
/// Retourne `None` si le caractère n'est pas supporté.
pub const fn char_to_glyph(c: u8) -> Option<usize> {
    match c {
        b'0'..=b'9' => Some((c - b'0') as usize),
        b'A'..=b'Z' => Some((c - b'A') as usize + LETTER_A),
        b'a'..=b'z' => Some((c - b'a') as usize + LETTER_A),
        b'-' => Some(MINUS),
        b' ' => Some(SPACE),
        b'.' => Some(DOT),
        b'(' => Some(LPAREN),
        b')' => Some(RPAREN),
        b',' => Some(COMMA),
        b'[' => Some(LBRACKET),
        b']' => Some(RBRACKET),
        b'%' => Some(PERCENT),
        b'<' => Some(LT),
        b'>' => Some(GT),
        b'=' => Some(EQUAL),
        b'?' => Some(QUESTION),
        b'!' => Some(EXCLAMATION),
        b':' => Some(COLON),
        b'+' => Some(PLUS),
        b'/' => Some(SLASH),
        b'|' => Some(PIPE),
        b'_' => Some(UNDERSCORE),
        b'^' => Some(CARET),
        b'#' => Some(HASH),
        b'@' => Some(AT),
        b'&' => Some(AMPERSAND),
        b'"' => Some(QUOTE),
        b'*' => Some(ASTERISK),
        b'\'' => Some(APOSTROPHE),
        b';' => Some(SEMICOLON),
        b'{' => Some(LBRACE),
        b'}' => Some(RBRACE),
        b'\\' => Some(BACKSLASH),
        b'~' => Some(TILDE),
        b'$' => Some(DOLLAR),
        b'`' => Some(BACKTICK),
        _ => None,
    }
}


/// Convertit un caractère Unicode en index de glyphe.
///
/// Supporte tout l'ASCII géré par [`char_to_glyph`], plus les symboles
/// mathématiques (`× ÷ ± ° ≤ ≥ ≠ ≈ √ ∞ ∫ ∂ →`) et les lettres grecques
/// `α β Δ θ λ μ π σ Σ φ ω Ω`. Retourne `None` sinon.
///
/// Les majuscules grecques sans glyphe dédié (`Π`, `Λ`, `Θ`, `Φ`…) ne sont
/// volontairement pas gérées pour l'instant.
pub const fn char_to_glyph_unicode(c: char) -> Option<usize> {
    match c {
        '×' => Some(TIMES),
        '÷' => Some(DIVIDE),
        '±' => Some(PLUS_MINUS),
        '°' => Some(DEGREE),
        '≤' => Some(LEQ),
        '≥' => Some(GEQ),
        '≠' => Some(NEQ),
        '≈' => Some(APPROX),
        '√' => Some(SQRT),
        '∞' => Some(INFINITY),
        'π' => Some(PI),
        'λ' => Some(LAMBDA),
        'θ' | 'ϑ' => Some(THETA),
        'μ' | 'µ' => Some(MU),
        'α' => Some(ALPHA),
        'β' => Some(BETA),
        'Δ' => Some(DELTA),
        'Σ' => Some(SIGMA),
        'Ω' => Some(OMEGA),
        'φ' | 'ϕ' => Some(PHI),
        'ω' => Some(LOWER_OMEGA),
        'σ' => Some(SIGMA_LOWER),
        '∫' => Some(INTEGRAL),
        '∂' => Some(PARTIAL),
        '→' => Some(ARROW_RIGHT),
        c if c.is_ascii() => char_to_glyph(c as u8),
        _ => None,
    }
}